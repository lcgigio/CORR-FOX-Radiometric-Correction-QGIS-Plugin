class FerramentaRotacionarAlvo(QgsMapTool):
    """Allows rotating the target square before confirming it."""
    def __init__(self, canvas, geometria_base, centro, funcao_retorno, funcao_cancelar=None):
        super().__init__(canvas)
        self.canvas = canvas
        self.geometria_base = geometria_base
        self.centro = centro
        self.funcao_retorno = funcao_retorno
        self.funcao_cancelar = funcao_cancelar
        self.angulo_atual = 0.0

        from qgis.gui import QgsRubberBand
        from qgis.core import Qgis
        from qgis.PyQt.QtGui import QCursor, QColor
        from qgis.PyQt.QtCore import Qt
        self.setCursor(QCursor(Qt.CursorShape.CrossCursor))

        self.rubber_band = QgsRubberBand(self.canvas, Qgis.GeometryType.PolygonGeometry)
        self.rubber_band.setColor(QColor(0, 120, 255, 90))
        self.rubber_band.setWidth(2)
        self.rubber_band.setToGeometry(self.geometria_base, None)
        self.rubber_band.show()

    def canvasMoveEvent(self, event):
        import math
        ponto_mouse = self.toMapCoordinates(event.pos())
        dx = ponto_mouse.x() - self.centro.x()
        dy = ponto_mouse.y() - self.centro.y()
        if dx == 0 and dy == 0:
            return
        self.angulo_atual = math.degrees(math.atan2(dx, dy))
        self._atualizar_previa()

    def _atualizar_previa(self):
        from qgis.core import QgsGeometry
        geom_rotacionada = QgsGeometry(self.geometria_base)
        geom_rotacionada.rotate(self.angulo_atual, self.centro)
        self.rubber_band.setToGeometry(geom_rotacionada, None)

    def canvasReleaseEvent(self, event):
        from qgis.PyQt.QtCore import Qt
        if event.button() == Qt.MouseButton.RightButton:
            self.angulo_atual = 0.0
            self._atualizar_previa()
            return
        self._finalizar()

    def canvasDoubleClickEvent(self, event):
        self._finalizar()

    def keyPressEvent(self, event):
        from qgis.PyQt.QtCore import Qt
        if event.key() == Qt.Key.Key_Escape:
            self._cancelar()
        elif event.key() in (Qt.Key.Key_Return, Qt.Key.Key_Enter):
            self._finalizar()

    def _finalizar(self):
        from qgis.core import QgsGeometry
        geom_final = QgsGeometry(self.geometria_base)
        geom_final.rotate(self.angulo_atual, self.centro)
        self._limpar_rubberband()
        self.funcao_retorno(geom_final)

    def _cancelar(self):
        self._limpar_rubberband()
        self.canvas.unsetMapTool(self)
        if self.funcao_cancelar:
            self.funcao_cancelar()

    def _limpar_rubberband(self):
        self.rubber_band.reset()
        self.canvas.scene().removeItem(self.rubber_band)


