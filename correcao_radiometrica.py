    def _calcular_linha_empirica_impl(self):
        if self.contador_alvos < 2:
            QMessageBox.warning(self.dlg, "Insufficient Data", "You need to register at least 2 targets.")
            return

        self.ganhos_por_banda.clear()
        self.offsets_por_banda.clear()
        self.equacoes_bandas.clear()
        
        tipo_regressao = self.dlg.cbTipoRegressao.currentIndex() if hasattr(self.dlg, 'cbTipoRegressao') else 0
        relatorio_modelo = "=== EQUATIONS GENERATED BY BAND ===\n\n"

        for banda in self.caminhos_bandas.keys():
            X, Y = [], []
            if hasattr(self.dlg, 'tabelaPontos') and hasattr(self.dlg, 'tabelaReflectancias'):
                for i in range(self.dlg.tabelaPontos.rowCount()):
                    if self.dlg.tabelaPontos.item(i, 2).text() == banda:
                        placa = self.dlg.tabelaPontos.item(i, 1).text()
                        dn_med = float(self.dlg.tabelaPontos.item(i, 6).text())
                        
                        for j in range(self.dlg.tabelaReflectancias.rowCount()):
                            if (self.dlg.tabelaReflectancias.item(j, 0).text() == banda and 
                                self.dlg.tabelaReflectancias.item(j, 1).text() == placa):
                                X.append(dn_med)
                                Y.append(float(self.dlg.tabelaReflectancias.item(j, 2).text()))
                                break
            n = len(X)
            if n < 2:
                continue

            if tipo_regressao == 0:
                mx, my = sum(X)/n, sum(Y)/n
                num = sum((X[i]-mx)*(Y[i]-my) for i in range(n))
                den = sum((X[i]-mx)**2 for i in range(n))
                ganho = num / den if den != 0 else 0.0
                offset = my - (ganho * mx)
            else:
                num = sum(X[i]*Y[i] for i in range(n))
                den = sum(X[i]**2 for i in range(n))
                ganho = num / den if den != 0 else 0.0
                offset = 0.0

            self.ganhos_por_banda[banda] = ganho
            self.offsets_por_banda[banda] = offset

            sinal = f"+ {offset:.6f}" if offset >= 0 else f"- {abs(offset):.6f}"
            eq_str = f"Reflectance = ({ganho:.6f} * DN) {sinal}"
            self.equacoes_bandas[banda] = eq_str
            relatorio_modelo += f"Band {banda}: {eq_str}\n"

        # Fills in the polygon data for reports/summary
        self.dados_poligonos = [
            {'id': item['id'], 'classe': f"Target {item['id']}", 'area': f"{item['geometria'].area():.2f}"}
            for item in self.lista_geometrias_alvos
        ]
        self.atualizar_exibicao_resultados(self.equacoes_bandas, self.dados_poligonos)

        QMessageBox.information(self.dlg, "Modeling Completed", relatorio_modelo)

        from qgis.PyQt.QtWidgets import QProgressDialog, QApplication
        from qgis.core import QgsRasterLayer
        from qgis.analysis import QgsRasterCalculator, QgsRasterCalculatorEntry

        progress = QProgressDialog("Applying radiometric correction...", "Cancel", 0, len(self.caminhos_bandas), self.dlg)
        progress.setWindowTitle("Processing")
        progress.setMinimumDuration(0)
        progress.setAutoClose(True)
        progress.setAutoReset(True)
        progress.show()

        QCoreApplication.processEvents()
        QApplication.setOverrideCursor(Qt.CursorShape.WaitCursor)

        try:
            for idx, (nome_banda, identificador) in enumerate(self.caminhos_bandas.items()):
                if nome_banda not in self.ganhos_por_banda:
                    continue
                if progress.wasCanceled():
                    break

                progress.setValue(idx)
                progress.setLabelText(f"Processing band {nome_banda}...")
                QCoreApplication.processEvents()

                camada_raster = None
                camadas = QgsProject.instance().mapLayersByName(identificador)
                if camadas:
                    camada_raster = camadas[0]
                else:
                    if os.path.exists(identificador):
                        camada_raster = QgsRasterLayer(identificador, f"Temp_{nome_banda}")
                
                if not camada_raster or not camada_raster.isValid():
                    continue

                ganho = self.ganhos_por_banda[nome_banda]
                offset = self.offsets_por_banda[nome_banda]

                nome_ref = camada_raster.name()
                ref_banda = f"{nome_ref}@1"
                
                sinal = f"+ {offset:.8f}" if offset >= 0 else f"- {abs(offset):.8f}"
                expressao_A = f"({ganho:.8f} * \"{ref_banda}\" {sinal})"
                expressao_normalizada = (
                    f"(({expressao_A} > 0) * ({expressao_A} < 1)) * {expressao_A} + "
                    f"({expressao_A} >= 1) * 1.0 + ({expressao_A} <= 0) * 0.0"
                )

                # QgsRasterCalculator directly (stable API) instead of
                # processing.run("qgis:rastercalculator"), a legacy algorithm
                # that is being retired in newer QGIS versions.
                entrada = QgsRasterCalculatorEntry()
                entrada.ref = ref_banda
                entrada.raster = camada_raster
                entrada.bandNumber = 1

                pasta_temp = tempfile.mkdtemp(prefix="corr_rad_")
                caminho_saida = os.path.join(pasta_temp, f"Band_{nome_banda}_Corrected.tif")

                calculadora = QgsRasterCalculator(
                    expressao_normalizada,
                    caminho_saida,
                    "GTiff",
                    camada_raster.extent(),
                    camada_raster.crs(),
                    camada_raster.width(),
                    camada_raster.height(),
                    [entrada],
                    QgsProject.instance().transformContext()
                )
                calculadora.processCalculation()

                nova_camada = QgsRasterLayer(caminho_saida, f"Band_{nome_banda}_Corrected")
                if not nova_camada.isValid():
                    raise RuntimeError(
                        f"Failed to generate the corrected raster for band {nome_banda}."
                    )

                if nova_camada and nova_camada.isValid():
                    QgsProject.instance().addMapLayer(nova_camada)

                QCoreApplication.processEvents()

            progress.setValue(len(self.caminhos_bandas))

        except Exception as e:
            QMessageBox.critical(self.dlg, "Error during correction", str(e))
        finally:
            progress.close()
            QApplication.restoreOverrideCursor()

        self.atualizar_tela_resultados()
        QMessageBox.information(self.dlg, "Status", "Correction finished!")

