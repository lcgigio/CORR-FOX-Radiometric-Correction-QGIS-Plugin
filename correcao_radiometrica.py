    def atualizar_tela_resultados(self):
        """Generates independent visual panels with charts and equations."""
        from qgis.PyQt.QtWidgets import QHBoxLayout, QTextEdit, QFrame

        if self.layout_scroll:
            for i in reversed(range(self.layout_scroll.count())):
                widget = self.layout_scroll.itemAt(i).widget()
                if widget and widget != getattr(self.dlg, 'txt_summary', None):
                    widget.setParent(None)

        self.lista_figuras_geradas.clear()
        self.relatorio_texto_completo = "=== MULTI-BAND CALIBRATION REPORT ===\n\n"

        if not self.ganhos_por_banda:
            return

        for banda in self.caminhos_bandas.keys():
            if banda not in self.ganhos_por_banda:
                continue

            ganho = self.ganhos_por_banda[banda]
            offset = self.offsets_por_banda[banda]

            X, Y, labels = [], [], []
            if hasattr(self.dlg, 'tabelaPontos') and hasattr(self.dlg, 'tabelaReflectancias'):
                for i in range(self.dlg.tabelaPontos.rowCount()):
                    b_item = self.dlg.tabelaPontos.item(i, 2)
                    p_item = self.dlg.tabelaPontos.item(i, 1)
                    dn_item = self.dlg.tabelaPontos.item(i, 6)

                    if b_item and p_item and dn_item and b_item.text() == banda:
                        placa = p_item.text()
                        try:
                            dn_val = float(dn_item.text())
                        except ValueError:
                            continue

                        ref_val = None
                        for j in range(self.dlg.tabelaReflectancias.rowCount()):
                            rb_item = self.dlg.tabelaReflectancias.item(j, 0)
                            rp_item = self.dlg.tabelaReflectancias.item(j, 1)
                            rv_item = self.dlg.tabelaReflectancias.item(j, 2)
                            if rb_item and rp_item and rv_item and rb_item.text() == banda and rp_item.text() == placa:
                                try:
                                    ref_val = float(rv_item.text())
                                except ValueError:
                                    pass
                                break

                        if ref_val is not None:
                            X.append(dn_val)
                            Y.append(ref_val)
                            labels.append(placa)

            sinal = f"+ {offset:.6f}" if offset >= 0 else f"- {abs(offset):.6f}"
            texto_banda = (
                f"BAND: {banda}\n"
                f"Equation: Reflectance = ({ganho:.6f} * DN) {sinal}\n\n"
                f"Collected Points:\n"
            )
            for i in range(len(X)):
                texto_banda += f" - {labels[i]} -> DN: {X[i]:.2f} | Reflectance: {Y[i]:.4f}\n"

            self.relatorio_texto_completo += texto_banda + "\n" + "="*50 + "\n\n"

            figura = Figure(figsize=(5, 3.5), dpi=90)
            ax = figura.add_subplot(111)

            if X and Y:
                ax.scatter(X, Y, color='red', marker='o', s=80, label='Targets', zorder=5)
                for idx, txt in enumerate(labels):
                    ax.annotate(txt, (X[idx], Y[idx]), xytext=(5, 5), textcoords='offset points', fontsize=8)

                x_reta = [min(X) * 0.9, max(X) * 1.1]
                y_reta = [ganho * x + offset for x in x_reta]
                ax.plot(x_reta, y_reta, color='blue', linestyle='--', linewidth=2, label='Fit Line')

            ax.set_title(f"Regression - {banda}", fontsize=11, fontweight='bold')
            ax.set_xlabel("Digital Number (DN)")
            ax.set_ylabel("Reflectance")
            ax.grid(True, linestyle=':', alpha=0.5)
            figura.tight_layout()

            self.lista_figuras_geradas.append((banda, figura))

            canvas = FigureCanvas(figura)
            canvas.draw()

            container = QFrame()
            container.setFrameShape(QFrame.Shape.StyledPanel)
            layout = QHBoxLayout(container)
            layout.addWidget(canvas, stretch=3)

            box = QTextEdit()
            box.setPlainText(texto_banda)
            box.setReadOnly(True)
            layout.addWidget(box, stretch=2)

            if self.layout_scroll:
                self.layout_scroll.addWidget(container)

        if self.conteudo_scroll:
            self.conteudo_scroll.update()
