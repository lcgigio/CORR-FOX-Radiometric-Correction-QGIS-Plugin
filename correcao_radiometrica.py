    def importar_arquivo_reflectancias(self):
        """Reads a TXT/CSV file of reflectances."""
        if not hasattr(self.dlg, 'tabelaReflectancias'):
            return
        from qgis.PyQt.QtWidgets import QFileDialog, QMessageBox, QTableWidgetItem
        import re
        
        arquivo, _ = QFileDialog.getOpenFileName(self.dlg, "Import Reflectances", "", "Text Files (*.txt *.csv)")
        if not arquivo: 
            return

        try:
            try:
                with open(arquivo, 'r', encoding='utf-8-sig') as f:
                    linhas = f.readlines()
            except UnicodeDecodeError:
                with open(arquivo, 'r', encoding='windows-1252') as f:
                    linhas = f.readlines()

            dados_importados = []
            for linha in linhas:
                if ';' in linha:
                    partes = linha.split(';')
                elif ',' in linha:
                    partes = linha.split(',')
                else:
                    continue
                    
                if len(partes) >= 3:
                    bnd = re.sub(r'[^a-z]', '', partes[0].lower())
                    plc = re.sub(r'[^a-z0-9]', '', partes[1].lower())
                    val_str = re.sub(r'[^\d.,]', '', partes[2])
                    
                    if not bnd or not val_str: 
                        continue
                        
                    try:
                        val = float(val_str.replace(',', '.'))
                        dados_importados.append((bnd, plc, val))
                    except ValueError:
                        continue

            valores_inseridos = 0
            for i in range(self.dlg.tabelaReflectancias.rowCount()):
                item_banda = self.dlg.tabelaReflectancias.item(i, 0)
                item_placa = self.dlg.tabelaReflectancias.item(i, 1)
                
                if not item_banda or not item_placa:
                    continue
                    
                banda_tabela = re.sub(r'[^a-z]', '', item_banda.text().lower())
                placa_tabela = re.sub(r'[^a-z0-9]', '', item_placa.text().lower())

                for bnd_txt, plc_txt, val_txt in dados_importados:
                    if bnd_txt in banda_tabela and plc_txt in placa_tabela:
                        self.dlg.tabelaReflectancias.setItem(i, 2, QTableWidgetItem(f"{val_txt:.4f}"))
                        valores_inseridos += 1
                        break

            if valores_inseridos == 0:
                QMessageBox.warning(self.dlg, "Compatibility Warning", "No compatible values were found in the file to fill the table.")
            else:
                QMessageBox.information(self.dlg, "Success", f"{valores_inseridos} values were filled in successfully.")

        except Exception as e:
            QMessageBox.critical(self.dlg, "Error", f"An unexpected error occurred:\n{str(e)}")

