    def salvar_alvos_shapefile(self):
        """Exports the drawn rectangles to a Shapefile."""
        from qgis.core import (QgsVectorLayer, QgsFeature, QgsField, 
                               QgsVectorFileWriter, QgsProject)
        from qgis.PyQt.QtWidgets import QFileDialog, QMessageBox
        
        if not hasattr(self, 'lista_geometrias_alvos') or not self.lista_geometrias_alvos:
            QMessageBox.information(self.dlg, "Warning", "There are no drawn polygons to save.")
            return

        caminho_shp, _ = QFileDialog.getSaveFileName(
            self.dlg, "Save Calibration Targets", "", "Shapefile (*.shp)"
        )
        if not caminho_shp:
            return

        crs = self.iface.mapCanvas().mapSettings().destinationCrs().authid()
        camada_temp = QgsVectorLayer(f"Polygon?crs={crs}", "Targets_Temp", "memory")
        provedor = camada_temp.dataProvider()
        provedor.addAttributes([QgsField("id", TIPO_CAMPO_INT), QgsField("name", TIPO_CAMPO_TEXTO)])
        camada_temp.updateFields()

        features = []
        for alvo in self.lista_geometrias_alvos:
            feat = QgsFeature()
            feat.setGeometry(alvo['geometria'])
            nome_alvo = f"Target {alvo['id']}"
            if hasattr(self.dlg, 'tabelaPontos'):
                for linha in range(self.dlg.tabelaPontos.rowCount()):
                    id_tabela = self.dlg.tabelaPontos.item(linha, 0).text()
                    if id_tabela == str(alvo['id']):
                        nome_alvo = self.dlg.tabelaPontos.item(linha, 1).text()
                        break

            feat.setAttributes([alvo['id'], nome_alvo])
            features.append(feat)

        provedor.addFeatures(features)
        camada_temp.updateExtents()

        opcoes = QgsVectorFileWriter.SaveVectorOptions()
        opcoes.driverName = "ESRI Shapefile"
        
        resultado_escrita = QgsVectorFileWriter.writeAsVectorFormatV3(
            camada_temp, caminho_shp, 
            QgsProject.instance().transformContext(), opcoes
        )
        erro = resultado_escrita[0]  # V3 returns (error, message, file, layer)
        
        if erro == QgsVectorFileWriter.WriterError.NoError:
            nome_arquivo = caminho_shp.split("/")[-1].replace(".shp", "")
            self.iface.addVectorLayer(caminho_shp, f"Targets - {nome_arquivo}", "ogr")
            QMessageBox.information(self.dlg, "Success", "Shapefile saved successfully and loaded into the map!")
        else:
            QMessageBox.critical(self.dlg, "Error", "Error saving the Shapefile.")

