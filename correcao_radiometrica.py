class FerramentaDesenharAlvoVertices(QgsMapTool):
    """Tool to draw a polygon by clicking vertex by vertex on the map."""
    def __init__(self, canvas, funcao_retorno):
        super().__init__(canvas)
        self.canvas = canvas
        self.funcao_retorno = funcao_retorno
        self.pontos = []

        from qgis.gui import QgsRubberBand
        from qgis.core import Qgis
        from qgis.PyQt.QtGui import QCursor, QColor
        from qgis.PyQt.QtCore import Qt
        self.setCursor(QCursor(Qt.CursorShape.CrossCursor))

        self.rubber_band = QgsRubberBand(self.canvas, Qgis.GeometryType.PolygonGeometry)
        self.rubber_band.setColor(QColor(255, 0, 0, 80))
        self.rubber_band.setWidth(2)

    def canvasReleaseEvent(self, event):
        from qgis.PyQt.QtCore import Qt
        if event.button() == Qt.MouseButton.RightButton:
            self.finalizar_poligono()
            return
        ponto_mapa = self.toMapCoordinates(event.pos())
        self.pontos.append(ponto_mapa)
        self._atualizar_previa()

    def canvasDoubleClickEvent(self, event):
        self.finalizar_poligono()

    def canvasMoveEvent(self, event):
        if not self.pontos:
            return
        ponto_mapa = self.toMapCoordinates(event.pos())
        self._atualizar_previa(ponto_extra=ponto_mapa)

    def keyPressEvent(self, event):
        from qgis.PyQt.QtCore import Qt
        if event.key() == Qt.Key.Key_Escape:
            self.cancelar()

    def _atualizar_previa(self, ponto_extra=None):
        from qgis.core import QgsGeometry
        pontos_previa = list(self.pontos)
        if ponto_extra is not None:
            pontos_previa.append(ponto_extra)
        if len(pontos_previa) >= 2:
            self.rubber_band.setToGeometry(QgsGeometry.fromPolygonXY([pontos_previa]), None)
            self.rubber_band.show()

    def finalizar_poligono(self):
        if len(self.pontos) < 3:
            self.cancelar()
            return
        from qgis.core import QgsGeometry
        geometria_final = QgsGeometry.fromPolygonXY([self.pontos])
        self.rubber_band.reset()
        self.canvas.scene().removeItem(self.rubber_band)
        self.pontos = []
        self.funcao_retorno(geometria_final)

    def cancelar(self):
        self.pontos = []
        self.rubber_band.reset()
        self.canvas.scene().removeItem(self.rubber_band)
        self.canvas.unsetMapTool(self)


